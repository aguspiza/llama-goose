"""Generate llama/vocab_pre.goose from llama.cpp's src/llama-vocab.h and .cpp:
the BPE pre-tokenizer types, what each tokenizer.ggml.pre name sets, and the
regexes each type splits with. These change with almost every new model, so
they are generated rather than ported by hand.

    python scripts/gen-vocab-pre.py <llama.cpp>/src llama/vocab_pre.goose
"""
import re
import sys


def cpp_strings(text):
    """The C++ string literals in text, in order, adjacent ones joined.
    Their escapes are the same in Goose, so the text between the quotes is
    kept as written."""
    out = []
    i = 0
    adjacent = False
    while i < len(text):
        if text.startswith("//", i):
            i = text.index("\n", i) if "\n" in text[i:] else len(text)
            continue
        c = text[i]
        if c == '"':
            j = i + 1
            while text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            lit = text[i + 1:j]
            if adjacent:
                out[-1] += lit
            else:
                out.append(lit)
            adjacent = True
            i = j + 1
            continue
        if not c.isspace():
            adjacent = False
        i += 1
    return out


def enum_values(header):
    body = re.search(r"enum llama_vocab_pre_type \{(.*?)\};", header, re.S).group(1)
    return re.findall(r"LLAMA_VOCAB_PRE_TYPE_(\w+)\s*=\s*(\d+)", body)


def goose_name(cpp_value):
    return "PRE_" + cpp_value.replace("LLAMA_VOCAB_PRE_TYPE_", "")


# What a statement in a pre-tokenizer branch of load() becomes.
def goose_statement(stmt):
    stmt = stmt.strip()
    m = re.fullmatch(r"pre_type = (LLAMA_VOCAB_PRE_TYPE_\w+)", stmt)
    if m:
        return f"pre_type = {goose_name(m.group(1))};"
    m = re.fullmatch(r"([\w.]+) = (true|false|LLAMA_TOKEN_NULL)", stmt)
    if m:
        name = m.group(1).replace("normalizer_opts.", "normalizer_")
        value = "TOKEN_NULL" if m.group(2) == "LLAMA_TOKEN_NULL" else m.group(2)
        return f"{name} = {value};"
    raise SystemExit(f"gen-vocab-pre: unknown statement in a pre-tokenizer branch: {stmt}")


def pre_names(source):
    """(names, statements) for each `tokenizer_pre == ...` branch of load()."""
    start = source.index("if (tokenizer_pre.empty())")
    end = source.index("} else if (type == LLAMA_VOCAB_TYPE_SPM)", start)
    block = source[start:end]
    branches = []
    for m in re.finditer(r"if \(\s*((?:tokenizer_pre == \"[^\"]*\"\s*(?:\|\|\s*)?)+)\)\s*\{(.*?)\}", block, re.S):
        names = re.findall(r'tokenizer_pre == "([^"]*)"', m.group(1))
        body = re.sub(r"//[^\n]*", "", m.group(2))
        stmts = [goose_statement(s) for s in body.split(";") if s.strip()]
        branches.append((names, stmts))
    return branches


def pre_regexes(source):
    """(types, regexes, byte_encode) for each case of the BPE tokenizer's switch."""
    start = source.index("struct llm_tokenizer_bpe : llm_tokenizer {")
    start = source.index("switch (vocab.get_pre_type())", start)
    end = source.index("std::vector<std::string> regex_exprs;", start)
    block = source[start:end]
    groups = []
    types = []
    for part in re.split(r"(case LLAMA_VOCAB_PRE_TYPE_\w+:|default:)", block)[1:]:
        if part.startswith("case "):
            types.append(goose_name(part[5:-1]))
            continue
        if part == "default:":
            types.append("default")
            continue
        m = re.search(r"regex_exprs = \{(.*?)\};", part, re.S)
        if not m:
            continue            # a case that falls through to the next one
        byte_encode = "byte_encode = false" not in part
        groups.append((types, cpp_strings(m.group(1)), byte_encode))
        types = []
    return groups


def main():
    src, dst = sys.argv[1], sys.argv[2]
    header = open(f"{src}/llama-vocab.h", encoding="utf-8").read()
    source = open(f"{src}/llama-vocab.cpp", encoding="utf-8").read()

    out = [
        "// Generated by scripts/gen-vocab-pre.py from llama.cpp src/llama-vocab.h and .cpp.",
        "// port-of: src/llama-vocab.h",
        "namespace vocab;",
        "",
        "// enum llama_vocab_pre_type",
    ]
    for name, value in enum_values(header):
        out.append(f"let PRE_{name} = {value};")

    out += [
        "",
        "// What a BPE vocab's tokenizer.ggml.pre name sets; false for an unknown name.",
        "// The empty name (default, with a warning) is handled by the caller.",
        "fn apply_pre_name(name: const u8[:]) -> bool {",
    ]
    for names, stmts in pre_names(source):
        cond = " || ".join(f'name == "{n}"' for n in names)
        out.append(f"    if {cond} {{")
        for s in stmts:
            out.append(f"        {s}")
        out.append("        return true;")
        out.append("    }")
    out += ["    return false;", "}", ""]

    groups = pre_regexes(source)
    for k, (types, regexes, byte_encode) in enumerate(groups):
        out.append(f"let PRE_REGEXES_{k} = [")
        for r in regexes:
            out.append(f'    "{r}",')
        out.append("];")
    out += [
        "",
        "// The regexes a BPE pre-tokenizer type splits text with, and whether",
        "// its words are then written in GPT-2's byte-level encoding.",
        "fn pre_regexes(t: i64) -> const u8[:][:], bool {",
    ]
    default = None
    for k, (types, regexes, byte_encode) in enumerate(groups):
        named = [t for t in types if t != "default"]
        if "default" in types:
            default = (k, byte_encode)
        if named:
            cond = " || ".join(f"t == {t}" for t in named)
            out.append(f"    if {cond} {{ return PRE_REGEXES_{k}, {'true' if byte_encode else 'false'}; }}")
    k, byte_encode = default
    out += [f"    return PRE_REGEXES_{k}, {'true' if byte_encode else 'false'};", "}", ""]

    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
