"""Convert llama.cpp's src/unicode-data.cpp into llama/unicode_data.goose
and its binary tables, llama/unicode_data.bin.

    python scripts/gen-unicode-data.py <llama.cpp>/src/unicode-data.cpp llama/unicode_data.goose

The C++ maps and sets become sorted arrays, searched by binary search in
llama/unicode.goose. They are embedded as one binary file because Goose
keeps only arrays of up to 256 elements in static data and builds larger
ones element by element when the program starts, a function gcc takes
half a minute to optimize.
"""
import re
import struct
import sys


def tables(source):
    """Each table's name and the integer tuples of its entries, in file order."""
    found = {}
    for match in re.finditer(r"\b(unicode_\w+) = \{(.*?)\n\};", source, re.S):
        name, body = match.groups()
        rows = []
        for line in body.splitlines():
            line = line.split("//")[0]
            numbers = re.findall(r"0x[0-9A-Fa-f]+|[0-9]+", line)
            if numbers:
                rows.append(tuple(int(n, 0) for n in numbers))
        found[name] = rows
    return found


def main():
    src, dst = sys.argv[1], sys.argv[2]
    bin_path = dst.rsplit(".", 1)[0] + ".bin"
    t = tables(open(src, encoding="utf-8").read())

    flags = t["unicode_ranges_flags"]
    lower = t["unicode_map_lowercase"]
    upper = t["unicode_map_uppercase"]
    nfd = t["unicode_ranges_nfd"]
    ccc = sorted(t["unicode_combining_class"])
    dec = sorted(t["unicode_decomposition"])
    comp = sorted(t["unicode_composition"])

    # name, element width in bytes, values, comment
    columns = [
        ("RANGE_START", 4, [r[0] for r in flags],
         "Codepoint ranges: a range starts at RANGE_START[i], has RANGE_FLAGS[i],\n// and ends where the next one starts."),
        ("RANGE_FLAGS", 2, [r[1] for r in flags], None),
        ("WHITESPACE_CPTS", 4, sorted(r[0] for r in t["unicode_set_whitespace"]), None),
        ("LOWER_FROM", 4, [r[0] for r in lower], "Case maps, sorted by the source codepoint."),
        ("LOWER_TO", 4, [r[1] for r in lower], None),
        ("UPPER_FROM", 4, [r[0] for r in upper], None),
        ("UPPER_TO", 4, [r[1] for r in upper], None),
        ("NFD_FIRST", 4, [r[0] for r in nfd], "NFD: codepoints NFD_FIRST[i]..NFD_LAST[i] map to NFD_TO[i]."),
        ("NFD_LAST", 4, [r[1] for r in nfd], None),
        ("NFD_TO", 4, [r[2] for r in nfd], None),
        ("CCC_CPT", 4, [r[0] for r in ccc], "Canonical combining classes, sorted by codepoint."),
        ("CCC_CLASS", 1, [r[1] for r in ccc], None),
        ("DEC_CPT", 4, [r[0] for r in dec], "Canonical decompositions: DEC_CPT[i] -> DEC_FIRST[i], DEC_SECOND[i] (0: none)."),
        ("DEC_FIRST", 4, [r[1] for r in dec], None),
        ("DEC_SECOND", 4, [r[2] for r in dec], None),
        ("COMP_PAIR", 8, [r[0] for r in comp], "Canonical compositions: the pair (first << 32 | second) -> COMP_TO[i]."),
        ("COMP_TO", 4, [r[1] for r in comp], None),
    ]
    fmt = {1: "<B", 2: "<H", 4: "<I", 8: "<Q"}

    blob = bytearray()
    out = [
        "// Generated by scripts/gen-unicode-data.py from llama.cpp src/unicode-data.cpp.",
        "// port-of: src/unicode-data.cpp",
        "namespace unicode;",
        "",
        'let DATA = embed_file("unicode_data.bin");',
        "",
        "// A column of little-endian unsigned integers in DATA.",
        "struct Table { off: i64, len: i64, width: i64 }",
        "",
        "fn at(t: Table, i: i64) -> u64 {",
        "    assert(0 <= i && i < t.len);",
        "    let p = t.off + i * t.width;",
        "    var v: u64 = 0;",
        "    for k in t.width { v |= (DATA[p + k] as u64) << (8 * k); }",
        "    return v;",
        "}",
        "",
        "// The first index whose value is > v (std::upper_bound).",
        "fn upper_bound(t: Table, v: u64) -> i64 {",
        "    var lo = 0;",
        "    var hi = t.len;",
        "    while lo < hi {",
        "        let mid = (lo + hi) / 2;",
        "        if at(t, mid) <= v { lo = mid + 1; } else { hi = mid; }",
        "    }",
        "    return lo;",
        "}",
        "",
        "// The index of v in a sorted column, and whether it is there.",
        "fn search(t: Table, v: u64) -> i64, bool {",
        "    let i = upper_bound(t, v) - 1;",
        "    return i, i >= 0 && at(t, i) == v;",
        "}",
        "",
    ]
    for name, width, values, comment in columns:
        while len(blob) % width:
            blob.append(0)
        if comment:
            out.append("// " + comment)
        out.append(f"let {name} = Table {{ off: {len(blob)}, len: {len(values)}, width: {width} }};")
        for v in values:
            blob += struct.pack(fmt[width], v)
    out.append("")

    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    with open(bin_path, "wb") as f:
        f.write(blob)


if __name__ == "__main__":
    main()
