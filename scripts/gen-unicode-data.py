"""Convert llama.cpp's src/unicode-data.cpp into llama/unicode_data.goose.

    python scripts/gen-unicode-data.py <llama.cpp>/src/unicode-data.cpp llama/unicode_data.goose

The C++ maps and sets become sorted arrays, searched by binary search in
llama/unicode.goose.
"""
import re
import sys


def tables(source):
    """Each table's name and the integer tuples of its entries, in file order."""
    found = {}
    for match in re.finditer(r"\b(unicode_\w+) = \{(.*?)\n\};", source, re.S):
        name, body = match.groups()
        rows = []
        for line in body.splitlines():
            line = line.split("//")[0]
            numbers = re.findall(r"0x[0-9A-Fa-f]+|[0-9]+", line)
            if numbers:
                rows.append(tuple(int(n, 0) for n in numbers))
        found[name] = rows
    return found


def goose_array(name, kind, values):
    lines = [f"const {name}: {kind}[{len(values)}] = ["]
    for i in range(0, len(values), 8):
        lines.append("    " + " ".join(f"0x{v:X}," for v in values[i:i + 8]))
    lines.append("];")
    return "\n".join(lines)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    t = tables(open(src, encoding="utf-8").read())

    flags = t["unicode_ranges_flags"]
    lower = t["unicode_map_lowercase"]
    upper = t["unicode_map_uppercase"]
    nfd = t["unicode_ranges_nfd"]
    ccc = sorted(t["unicode_combining_class"])
    dec = sorted(t["unicode_decomposition"])
    comp = sorted(t["unicode_composition"])

    out = [
        "// Generated by scripts/gen-unicode-data.py from llama.cpp src/unicode-data.cpp.",
        "// port-of: src/unicode-data.cpp",
        "namespace unicode;",
        "",
        "// Codepoint ranges: a range starts at RANGE_START[i], has RANGE_FLAGS[i],",
        "// and ends where the next one starts.",
        goose_array("RANGE_START", "u32", [r[0] for r in flags]),
        goose_array("RANGE_FLAGS", "u16", [r[1] for r in flags]),
        "",
        goose_array("WHITESPACE_CPTS", "u32", sorted(r[0] for r in t["unicode_set_whitespace"])),
        "",
        "// Case maps, sorted by the source codepoint.",
        goose_array("LOWER_FROM", "u32", [r[0] for r in lower]),
        goose_array("LOWER_TO", "u32", [r[1] for r in lower]),
        goose_array("UPPER_FROM", "u32", [r[0] for r in upper]),
        goose_array("UPPER_TO", "u32", [r[1] for r in upper]),
        "",
        "// NFD: codepoints NFD_FIRST[i]..NFD_LAST[i] map to NFD_TO[i].",
        goose_array("NFD_FIRST", "u32", [r[0] for r in nfd]),
        goose_array("NFD_LAST", "u32", [r[1] for r in nfd]),
        goose_array("NFD_TO", "u32", [r[2] for r in nfd]),
        "",
        "// Canonical combining classes, sorted by codepoint.",
        goose_array("CCC_CPT", "u32", [r[0] for r in ccc]),
        goose_array("CCC_CLASS", "u8", [r[1] for r in ccc]),
        "",
        "// Canonical decompositions: DEC_CPT[i] -> DEC_FIRST[i], DEC_SECOND[i] (0: none).",
        goose_array("DEC_CPT", "u32", [r[0] for r in dec]),
        goose_array("DEC_FIRST", "u32", [r[1] for r in dec]),
        goose_array("DEC_SECOND", "u32", [r[2] for r in dec]),
        "",
        "// Canonical compositions: the pair (first << 32 | second) -> COMP_TO[i].",
        goose_array("COMP_PAIR", "u64", [r[0] for r in comp]),
        goose_array("COMP_TO", "u32", [r[1] for r in comp]),
        "",
    ]
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
